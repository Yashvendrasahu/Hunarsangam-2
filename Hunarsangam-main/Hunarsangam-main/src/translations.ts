// Comprehensive multilingual translation dictionary for HunarSangam
// Supports: Hindi (hi), English (en), Marathi (mr), Gujarati (gu), Bengali (bn), Tamil (ta), Telugu (te)

export type SupportedLang = 'hi' | 'en' | 'mr' | 'gu' | 'bn' | 'ta' | 'te';

export function getLangCode(lang: string): SupportedLang {
  const l = (lang || '').toLowerCase();
  if (l.includes('hindi') || l.includes('हिंदी')) return 'hi';
  if (l.includes('marathi') || l.includes('मराठी')) return 'mr';
  if (l.includes('gujarati') || l.includes('ગુજરાતી')) return 'gu';
  if (l.includes('bengali') || l.includes('বাংলা')) return 'bn';
  if (l.includes('tamil') || l.includes('தமிழ்')) return 'ta';
  if (l.includes('telugu') || l.includes('తెలుగు')) return 'te';
  return 'en';
}

